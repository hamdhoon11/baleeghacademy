PG_NOW = "to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')"   # same text format as SQLite's datetime('now')
_ID_TABLE = re.compile(r"CREATE TABLE IF NOT EXISTS (\w+)\s*\(\s*id INTEGER PRIMARY KEY AUTOINCREMENT", re.I)

"""Database layer. One small API over two engines, so the rest of the portal does not care which one is used.

  * No DATABASE_URL  -> SQLite file (DATABASE_PATH). This is what local runs and the tests use.
  * DATABASE_URL set -> hosted PostgreSQL (Supabase, Neon, Render, Railway, ...).

The portal's SQL is written in SQLite style (`?` placeholders, `datetime('now')`, `INSERT OR IGNORE`, `cursor.lastrowid`).
For PostgreSQL this module translates those on the fly, so app.py, learning.py and fees.py are the same on both.
Dates and times are stored as TEXT on both engines (the app already writes them as text), so comparisons behave the same.
"""
import datetime as dt
import decimal
import hashlib
import os
import re
import sqlite3

try:  # psycopg is only needed when DATABASE_URL is set
    import psycopg
    from psycopg import errors as _pgerr
except ImportError:  # pragma: no cover - exercised only on machines without psycopg
    psycopg = None
    _pgerr = None

# Catch this (not sqlite3.IntegrityError) in app code: it covers both engines.
IntegrityError = (sqlite3.IntegrityError,) + ((psycopg.errors.IntegrityError,) if psycopg else ())

PG_NOW = "to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')"   # same text format as SQLite's datetime('now')
_ID_TABLE = re.compile(r"CREATE TABLE IF NOT EXISTS (\w+)\s*\(\s*id INTEGER PRIMARY KEY AUTOINCREMENT", re.I)
_LOCK_KEY = 727_001   # arbitrary number: stops two serverless instances from migrating the schema at the same moment


def is_postgres(url):
    return bool(url) and url.split(":", 1)[0] in ("postgres", "postgresql")


def normalise_url(url):
    """Some hosts hand out postgres://; psycopg wants postgresql://."""
    return "postgresql://" + url.split("://", 1)[1] if url.startswith("postgres://") else url


# ---------- rows and values ----------
class Row(dict):
    """A row you can read by column name, by position (row[0]) and convert with dict(row), like sqlite3.Row."""
    __slots__ = ("_vals",)

    def __init__(self, names, values):
        super().__init__(zip(names, values))
        self._vals = tuple(values)

    def __getitem__(self, k):
        return self._vals[k] if isinstance(k, int) else super().__getitem__(k)


def _py(v):
    """PostgreSQL returns Decimal for SUM()/AVG(); the app (and JSON) expect plain numbers, as SQLite gives."""
    if isinstance(v, decimal.Decimal):
        return int(v) if v == v.to_integral_value() else float(v)
    return v


def _arg(v):
    """Make a Python value safe to send to either engine (PostgreSQL is stricter than SQLite)."""
    if isinstance(v, bool): return int(v)                    # the schema stores flags as INTEGER 0/1
    if isinstance(v, dt.datetime): return v.isoformat(" ")   # dates and times are TEXT columns
    if isinstance(v, dt.date): return v.isoformat()
    return v


# ---------- SQL translation (SQLite style -> PostgreSQL) ----------
_STR = re.compile(r"('(?:[^']|'')*')")


def translate(sql, args, id_tables):
    """Return (pg_sql, args). Only used for PostgreSQL."""
    out = []
    for i, part in enumerate(_STR.split(sql)):
        if i % 2:                       # inside a '...' literal: keep as is, but a % must be doubled when parameters are used
            out.append(part.replace("%", "%%") if args else part)
        else:
            if args: part = part.replace("%", "%%").replace("?", "%s")
            out.append(re.sub(r"\bLIKE\b", "ILIKE", part, flags=re.I))   # SQLite LIKE ignores case; PostgreSQL LIKE does not
    s = "".join(out)
    s = re.sub(r"datetime\(\s*'now'\s*\)", PG_NOW, s, flags=re.I)
    st = s.lstrip()
    if re.match(r"INSERT\s+OR\s+IGNORE\s+INTO", st, re.I):
        s = re.sub(r"INSERT\s+OR\s+IGNORE\s+INTO", "INSERT INTO", s, count=1, flags=re.I)
        if not re.search(r"ON\s+CONFLICT", s, re.I): s += " ON CONFLICT DO NOTHING"
    return s, tuple(_arg(a) for a in args)


def schema_to_pg(script):
    s = re.sub(r"INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", script)
    s = re.sub(r"DEFAULT \(datetime\('now'\)\)", f"DEFAULT ({PG_NOW})", s)
    s = re.sub(r"\bREAL\b", "DOUBLE PRECISION", s)
    return s


# ---------- connections ----------
class Cur:
    """What db().execute(...) returns: fetchone/fetchall/iteration, plus lastrowid and rowcount like sqlite3."""

    def __init__(self, cur, lastrowid=None, pg=False):
        self._c, self._last, self._pg = cur, lastrowid, pg

    @property
    def lastrowid(self):
        return self._last if self._pg else self._c.lastrowid

    @property
    def rowcount(self):
        return self._c.rowcount

    def _wrap(self, r):
        if r is None: return None
        if not self._pg: return r            # sqlite3.Row already behaves as we need
        names = [d.name for d in self._c.description]
        return Row(names, [_py(v) for v in r])

    def fetchone(self):
        return self._wrap(self._c.fetchone())

    def fetchall(self):
        return [self._wrap(r) for r in self._c.fetchall()]

    def __iter__(self):
        return iter(self.fetchall())


class Conn:
    def __init__(self, url=None, path=None, id_tables=()):
        self.pg = is_postgres(url)
        self.id_tables = set(id_tables)
        if self.pg:
            if psycopg is None:
                raise RuntimeError("DATABASE_URL is set but the 'psycopg' package is not installed. Run: pip install \"psycopg[binary]\"")
            # prepare_threshold=None: poolers such as Supabase's and Neon's (pgbouncer, transaction mode) cannot keep prepared statements.
            self.raw = psycopg.connect(normalise_url(url), prepare_threshold=None, connect_timeout=10)
        else:
            self.raw = sqlite3.connect(path)
            self.raw.row_factory = sqlite3.Row
            self.raw.execute("PRAGMA foreign_keys=ON")

    def execute(self, sql, args=()):
        args = tuple(args)
        if not self.pg:
            return Cur(self.raw.execute(sql, tuple(_arg(a) for a in args)))
        s, a = translate(sql, args, self.id_tables)
        m = re.match(r"\s*INSERT\s+INTO\s+(\w+)", s, re.I)
        want_id = bool(m) and m.group(1).lower() in self.id_tables and not re.search(r"\bRETURNING\b", s, re.I)
        if want_id: s += " RETURNING id"
        cur = self.raw.cursor()
        cur.execute(s, a or None)
        last = None
        if want_id:
            r = cur.fetchone()
            last = r[0] if r else None
        return Cur(cur, last, pg=True)

    def executescript(self, script):
        if self.pg:
            self.raw.cursor().execute(schema_to_pg(script))
        else:
            self.raw.executescript(script)

    def columns(self, table):
        """Names of the columns a table has (empty set if it does not exist). Used for small upgrades of older databases."""
        if self.pg:
            r = self.raw.cursor().execute("SELECT column_name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=%s", (table,))
            return {x[0] for x in r.fetchall()}
        return {r[1] for r in self.raw.execute(f"PRAGMA table_info({table})")}

    def commit(self): self.raw.commit()
    def rollback(self): self.raw.rollback()
    def close(self): self.raw.close()

    def reset_sequences(self):
        """After rows were copied in with explicit ids, move each id counter past the largest id (PostgreSQL only)."""
        if not self.pg: return
        for t in sorted(self.id_tables):
            self.raw.cursor().execute(f"SELECT setval(pg_get_serial_sequence('{t}', 'id'), COALESCE((SELECT MAX(id) FROM {t}), 0) + 1, false)")
        self.raw.commit()


def read_schema(base):
    with open(os.path.join(base, "schema.sql")) as f:
        return f.read()


def id_tables_of(script):
    return {m.lower() for m in _ID_TABLE.findall(script)}


def connect(config, base, script=None):
    script = script if script is not None else read_schema(base)
    return Conn(config.get("DATABASE_URL"), config.get("DATABASE_PATH"), id_tables_of(script))


def init_schema(conn, base):
    """Create missing tables and add columns that older databases lack. Safe to run on every start; skipped when nothing changed."""
    script = read_schema(base)
    version = hashlib.sha1((script + "|v2-columns").encode()).hexdigest()[:16]
    if conn.pg:   # the lock lasts until the commit below, so two cold starts never migrate at the same moment
        conn.raw.cursor().execute("SELECT pg_advisory_xact_lock(%s)", (_LOCK_KEY,))
    conn.execute("CREATE TABLE IF NOT EXISTS schema_meta (id INTEGER PRIMARY KEY, version TEXT NOT NULL)")
    r = conn.execute("SELECT version FROM schema_meta WHERE id=1").fetchone()
    if r and r["version"] == version:
        conn.commit()
        return
    conn.executescript(script)
    # databases created before these columns existed: add them (CREATE TABLE IF NOT EXISTS does not)
    if "attachment" not in conn.columns("assignments"): conn.execute("ALTER TABLE assignments ADD COLUMN attachment TEXT")
    if "attachment_name" not in conn.columns("assignments"): conn.execute("ALTER TABLE assignments ADD COLUMN attachment_name TEXT")
    if "permissions" not in conn.columns("users"): conn.execute("ALTER TABLE users ADD COLUMN permissions TEXT")   # NULL = full admin
    if r:
        conn.execute("UPDATE schema_meta SET version=? WHERE id=1", (version,))
    else:
        conn.execute("INSERT INTO schema_meta(id,version) VALUES(1,?)", (version,))
    conn.commit()

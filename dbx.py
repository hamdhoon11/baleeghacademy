def is_postgres(url):
    return bool(url) and url.split(":", 1)[0] in ("postgres", "postgresql")


def normalise_url(url):
    """Some hosts hand out postgres://; psycopg wants postgresql://."""
    return "postgresql://" + url.split("://", 1)[1] if url.startswith("postgres://") else url


# ---------- rows and values ----------
class Row(dict):
    """A row you can read by column name, by position (row[0]) and convert with dict(row), like sqlite3.Row."""
    __slots__ = ("_vals",)

    def __init__(self, names, values):
        super().__init__(zip(names, values))
        self._vals = tuple(values)

    def __getitem__(self, k):
        return self._vals[k] if isinstance(k, int) else super().__getitem__(k)


def values(row):
    """A row as a plain tuple of its values, on both engines (v0.8.40). tuple(row) is NOT the same: on PostgreSQL a Row is a dict,
    so tuple(row) gives the column NAMES. That made the teacher earnings calculation fail on the hosted database only."""
    return row._vals if isinstance(row, Row) else tuple(row)


def _py(v):
    """PostgreSQL returns Decimal for SUM()/AVG(); the app (and JSON) expect plain numbers, as SQLite gives."""
    if isinstance(v, decimal.Decimal):
        return int(v) if v == v.to_integral_value() else float(v)
    return v


def _arg(v):
    """Make a Python value safe to send to either engine (PostgreSQL is stricter than SQLite)."""
    if isinstance(v, bool): return int(v)                    # the schema stores flags as INTEGER 0/1
    if isinstance(v, dt.datetime): return v.isoformat(" ")   # dates and times are TEXT columns
    if isinstance(v, dt.date): return v.isoformat()
    return v


# ---------- SQL translation (SQLite style -> PostgreSQL) ----------
_STR = re.compile(r"('(?:[^']|'')*')")


def translate(sql, args, id_tables):
    """Return (pg_sql, args). Only used for PostgreSQL."""
    out = []
    for i, part in enumerate(_STR.split(sql)):
        if i % 2:                       # inside a '...' literal: keep as is, but a % must be doubled when parameters are used
            out.append(part.replace("%", "%%") if args else part)
        else:
            if args: part = part.replace("%", "%%").replace("?", "%s")
            out.append(re.sub(r"\bLIKE\b", "ILIKE", part, flags=re.I))   # SQLite LIKE ignores case; PostgreSQL LIKE does not
    s = "".join(out)
    s = re.sub(r"datetime\(\s*'now'\s*\)", PG_NOW, s, flags=re.I)
    st = s.lstrip()
    if re.match(r"INSERT\s+OR\s+IGNORE\s+INTO", st, re.I):
        s = re.sub(r"INSERT\s+OR\s+IGNORE\s+INTO", "INSERT INTO", s, count=1, flags=re.I)
        if not re.search(r"ON\s+CONFLICT", s, re.I): s += " ON CONFLICT DO NOTHING"
    return s, tuple(_arg(a) for a in args)


def schema_to_pg(script):
    s = re.sub(r"INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", script)
    s = re.sub(r"DEFAULT \(datetime\('now'\)\)", f"DEFAULT ({PG_NOW})", s)
    s = re.sub(r"\bREAL\b", "DOUBLE PRECISION", s)
    s = re.sub(r"\bBLOB\b", "BYTEA", s)   # v0.8.34: stored_files.data
    return s


# ---------- connections ----------
class Cur:
    """What db().execute(...) returns: fetchone/fetchall/iteration, plus lastrowid and rowcount like sqlite3."""

    def __init__(self, cur, lastrowid=None, pg=False):
        self._c, self._last, self._pg = cur, lastrowid, pg

    @property
    def lastrowid(self):
        return self._last if self._pg else self._c.lastrowid

    @property
    def rowcount(self):
        return self._c.rowcount

    def _wrap(self, r):
        if r is None: return None
        if not self._pg: return r            # sqlite3.Row already behaves as we need
        names = [d.name for d in self._c.description]
        return Row(names, [_py(v) for v in r])

    def fetchone(self):
        return self._wrap(self._c.fetchone())

    def fetchall(self):
        return [self._wrap(r) for r in self._c.fetchall()]

    def __iter__(self):
        return iter(self.fetchall())



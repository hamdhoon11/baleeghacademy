def upgrade_v0845(conn):
    """Additive, and only loosens rules: three new invoice columns, NOT NULL dropped from the invoice's student/enrolment/course/batch and the
    payment's student. No row is changed. PostgreSQL: ALTER COLUMN ... DROP NOT NULL. SQLite cannot drop NOT NULL with ALTER TABLE, so the
    stored table definition is edited in place (the documented way for changes that leave the stored rows exactly as they are)."""
    for col, decl in (("customer_name", "TEXT"), ("customer_phone", "TEXT"), ("revenue_type_id", "INTEGER REFERENCES revenue_types(id)")):
        if col not in conn.columns("invoices"): conn.execute(f"ALTER TABLE invoices ADD COLUMN {col} {decl}")
    loosen = [("invoices", c) for c in V0845_INVOICE_NULLABLE if c in not_null_columns(conn, "invoices")]
    for t in ("payments", "payment_slips"):
        if "student_id" in not_null_columns(conn, t): loosen.append((t, "student_id"))
    if loosen and conn.pg:
        for t, c in loosen: conn.execute(f"ALTER TABLE {t} ALTER COLUMN {c} DROP NOT NULL")
    elif loosen:
        for t in sorted({t for t, _ in loosen}):
            sql = conn.raw.execute("SELECT sql FROM sqlite_master WHERE type='table' AND name=?", (t,)).fetchone()[0]
            new = sql
            for tt, c in loosen:
                if tt == t: new = re.sub(rf"(\b{c}\s+INTEGER)\s+NOT\s+NULL", r"\1", new, count=1)
            if new == sql: continue
            ver = conn.raw.execute("PRAGMA schema_version").fetchone()[0]
            conn.raw.execute("PRAGMA writable_schema=ON")
            conn.raw.execute("UPDATE sqlite_master SET sql=? WHERE type='table' AND name=?", (new, t))
            conn.raw.execute(f"PRAGMA schema_version={ver + 1}")
            conn.raw.execute("PRAGMA writable_schema=OFF")
        bad = conn.raw.execute("PRAGMA integrity_check").fetchone()[0]
        if bad != "ok": raise RuntimeError("v0.8.45 upgrade: integrity check failed: " + str(bad))
    for name, code in (("Monthly fees", "monthly"), ("Registration fees", "registration")):
        if not conn.execute("SELECT 1 FROM revenue_types WHERE code=?", (code,)).fetchone():
            taken = conn.execute("SELECT 1 FROM revenue_types WHERE name=?", (name,)).fetchone()
            conn.execute("INSERT INTO revenue_types(name, code, is_active, created_at) VALUES(?,?,1,?)", (name + (" (built-in)" if taken else ""), code, dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%M:%S")))


class Conn:
    def __init__(self, url=None, path=None, id_tables=()):
        self.pg = is_postgres(url)
        self.id_tables = set(id_tables)
        if self.pg:
            if psycopg is None:
                raise RuntimeError("DATABASE_URL is set but the 'psycopg' package is not installed. Run: pip install \"psycopg[binary]\"")
            # prepare_threshold=None: poolers such as Supabase's and Neon's (pgbouncer, transaction mode) cannot keep prepared statements.
            self.raw = psycopg.connect(normalise_url(url), prepare_threshold=None, connect_timeout=10)
        else:
            self.raw = sqlite3.connect(path)
            self.raw.row_factory = sqlite3.Row
            self.raw.execute("PRAGMA foreign_keys=ON")

    q = 0      # queries run and milliseconds spent on them since the last reset_stats(); shown in the Server-Timing header
    ms = 0.0

    def reset_stats(self):
        self.q, self.ms = 0, 0.0

    def execute(self, sql, args=()):
        t0 = time.perf_counter()
        try:
            return self._execute(sql, args)
        finally:
            self.q += 1
            self.ms += (time.perf_counter() - t0) * 1000

    def _execute(self, sql, args=()):
        args = tuple(args)
        if not self.pg:
            return Cur(self.raw.execute(sql, tuple(_arg(a) for a in args)))
        s, a = translate(sql, args, self.id_tables)
        m = re.match(r"\s*INSERT\s+INTO\s+(\w+)", s, re.I)
        want_id = bool(m) and m.group(1).lower() in self.id_tables and not re.search(r"\bRETURNING\b", s, re.I)
        if want_id: s += " RETURNING id"
        cur = self.raw.cursor()
        cur.execute(s, a or None)
        last = None
        if want_id:
            r = cur.fetchone()
            last = r[0] if r else None
        return Cur(cur, last, pg=True)

    def executescript(self, script):
        if self.pg:
            self.raw.cursor().execute(schema_to_pg(script))
        else:
            self.raw.executescript(script)

    def columns(self, table):
        """Names of the columns a table has (empty set if it does not exist). Used for small upgrades of older databases."""
        if self.pg:
            r = self.raw.cursor().execute("SELECT column_name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=%s", (table,))
            return {x[0] for x in r.fetchall()}
        return {r[1] for r in self.raw.execute(f"PRAGMA table_info({table})")}

    def commit(self): self.raw.commit()
    def rollback(self): self.raw.rollback()
    def close(self): self.raw.close()

    def reset_sequences(self):
        """After rows were copied in with explicit ids, move each id counter past the largest id (PostgreSQL only)."""
        if not self.pg: return
        for t in sorted(self.id_tables):
            self.raw.cursor().execute(f"SELECT setval(pg_get_serial_sequence('{t}', 'id'), COALESCE((SELECT MAX(id) FROM {t}), 0) + 1, false)")
        self.raw.commit()


def read_schema(base):
    with open(os.path.join(base, "schema.sql")) as f:
        return f.read()


def id_tables_of(script):
    return {m.lower() for m in _ID_TABLE.findall(script)}


def connect(config, base, script=None):
    script = script if script is not None else read_schema(base)
    return Conn(config.get("DATABASE_URL"), config.get("DATABASE_PATH"), id_tables_of(script))


def init_schema(conn, base):
    """Create missing tables and add columns that older databases lack. Safe to run on every start; skipped when nothing changed."""
    script = read_schema(base)
    version = hashlib.sha1((script + "|v5-audit-lock").encode()).hexdigest()[:16]
    if conn.pg:   # the lock lasts until the commit below, so two cold starts never migrate at the same moment
        conn.raw.cursor().execute("SELECT pg_advisory_xact_lock(%s)", (_LOCK_KEY,))
    conn.execute("CREATE TABLE IF NOT EXISTS schema_meta (id INTEGER PRIMARY KEY, version TEXT NOT NULL)")
    r = conn.execute("SELECT version FROM schema_meta WHERE id=1").fetchone()
    if r and r["version"] == version:
        conn.commit()
        return
    conn.executescript(script)
    # databases created before these columns existed: add them (CREATE TABLE IF NOT EXISTS does not)
    if "attachment" not in conn.columns("assignments"): conn.execute("ALTER TABLE assignments ADD COLUMN attachment TEXT")
    if "attachment_name" not in conn.columns("assignments"): conn.execute("ALTER TABLE assignments ADD COLUMN attachment_name TEXT")
    if "meet_link" not in conn.columns("sessions"): conn.execute("ALTER TABLE sessions ADD COLUMN meet_link TEXT")   # Session 4: one-off class link
    if "permissions" not in conn.columns("users"): conn.execute("ALTER TABLE users ADD COLUMN permissions TEXT")   # NULL = full admin
    # Session 10: course type, ID codes. Nullable or defaulted, so existing rows are untouched; idcodes.fill_missing() / migrate_session10.py fill the codes.
    for tbl, col, decl in (("courses", "kind", "TEXT NOT NULL DEFAULT 'course' CHECK (kind IN ('course','tuition'))"), ("courses", "code", "TEXT"),
                           ("courses", "is_active", "INTEGER NOT NULL DEFAULT 1"), ("students", "student_code", "TEXT"),
                           ("teachers", "teacher_code", "TEXT"), ("enrollments", "enrol_code", "TEXT")):
        if col not in conn.columns(tbl): conn.execute(f"ALTER TABLE {tbl} ADD COLUMN {col} {decl}")
    # Session 31: one-time registration fee on a course; invoice kind. Defaults keep every existing row exactly as it was (fee 0, monthly).
    if "registration_fee_mvr" not in conn.columns("courses"): conn.execute("ALTER TABLE courses ADD COLUMN registration_fee_mvr INTEGER NOT NULL DEFAULT 0 CHECK (registration_fee_mvr >= 0)")
    if "kind" not in conn.columns("invoices"): conn.execute("ALTER TABLE invoices ADD COLUMN kind TEXT NOT NULL DEFAULT 'monthly'")
    if "login_id" not in conn.columns("users"): conn.execute("ALTER TABLE users ADD COLUMN login_id TEXT")   # Session 11: what people type to sign in; idcodes.fill_missing() fills it
    # Session 20: activity log v2. Old rows keep working (all new columns are nullable); auditlog.backfill() fills what can be worked out.
    for col in ("user_role", "login_id", "course_id", "batch_id", "old_value", "new_value", "ip"):
        if col not in conn.columns("audit_log"): conn.execute(f"ALTER TABLE audit_log ADD COLUMN {col} {'INTEGER' if col.endswith('_id') and col != 'login_id' else 'TEXT'}")
    # v0.8.37: tutorial grading and recurring expenses. Additive only: existing tutorials get "out of 100", existing answers stay ungraded (migrate_v0837.py shows this first).
    for tbl, col, decl in V0837_COLUMNS:
        if col not in conn.columns(tbl): conn.execute(f"ALTER TABLE {tbl} ADD COLUMN {col} {schema_to_pg(decl) if conn.pg else decl}")
    upgrade_v0845(conn)
    for col, decl in V0847_USER_COLUMNS:
        if col not in conn.columns("users"): conn.execute(f"ALTER TABLE users ADD COLUMN {col} {decl}")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_audit_batch ON audit_log(batch_id)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_audit_user ON audit_log(user_id)")
    import auditlog; auditlog.install_triggers(conn)   # Session 21: the log can be added to but never changed or deleted
    for name, tbl, col in (("ux_users_login_id", "users", "login_id"), ("ux_courses_code", "courses", "code"), ("ux_students_code", "students", "student_code"),
                           ("ux_teachers_code", "teachers", "teacher_code"), ("ux_enrol_code", "enrollments", "enrol_code")):
        conn.execute(f"CREATE UNIQUE INDEX IF NOT EXISTS {name} ON {tbl}({col})")   # NULLs are allowed more than once on both engines
    # Session 2: people who were limited to some areas and could already open Tutorials keep what they could do before
    # (teachers/admins: post; students: now send answers). People with no limit (permissions NULL) get the new areas automatically.
    for u in conn.execute("SELECT id,role,permissions FROM users WHERE permissions IS NOT NULL").fetchall():
        have = [x for x in (u["permissions"] or "").split(",") if x]
        add = {"admin": "create_tutorials", "teacher": "create_tutorials", "student": "submit_tutorial_work"}.get(u["role"])
        if add and "tutorials" in have and add not in have:
            have = have + [add]
            conn.execute("UPDATE users SET permissions=? WHERE id=?", (",".join(have), u["id"]))
        # Session 4: a limited admin who could already edit batches could already set Meet links, so keeps doing so. Teachers could not, so they start without it.
        if u["role"] == "admin" and "batches" in have and "class_links" not in have:
            have = have + ["class_links"]
            conn.execute("UPDATE users SET permissions=? WHERE id=?", (",".join(have), u["id"]))
        # Session 5: a limited admin who could already use Classroom could already manage batch resources, so keeps adding recordings; a limited
        # student who could open Materials also gets Recordings. Limited teachers start without it (the superadmin ticks it in People).
        if u["role"] == "admin" and "classroom" in have and "add_recordings" not in have:
            have = have + ["add_recordings"]
            conn.execute("UPDATE users SET permissions=? WHERE id=?", (",".join(have), u["id"]))
        if u["role"] == "student" and "materials" in have and "recordings" not in have:
            have = have + ["recordings"]
            conn.execute("UPDATE users SET permissions=? WHERE id=?", (",".join(have), u["id"]))
    if r:
        conn.execute("UPDATE schema_meta SET version=? WHERE id=1", (version,))
    else:
        conn.execute("INSERT INTO schema_meta(id,version) VALUES(1,?)", (version,))
    conn.commit()

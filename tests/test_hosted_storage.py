"""Persistent storage: the PostgreSQL translation layer and the bucket file storage.

No real PostgreSQL server or bucket is used here. The SQL translation is checked directly, the PostgreSQL code path is run against a
recording fake driver, and the bucket is an in-memory fake with the same calls boto3 makes. Run check_storage.py once against your real
DATABASE_URL and bucket to prove the live connection (see README)."""
import datetime as dt, decimal, io, os, sys, tempfile, types, unittest
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import dbx, storage, common

PDF = b"%PDF-1.4 test"
BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IDS = dbx.id_tables_of(dbx.read_schema(BASE))


class Translate(unittest.TestCase):
    def t(self, sql, args=()):
        return dbx.translate(sql, tuple(args), IDS)

    def test_placeholders_and_percent(self):
        s, a = self.t("SELECT * FROM t WHERE a=? AND b LIKE ?", (1, "%x%"))
        self.assertEqual(s, "SELECT * FROM t WHERE a=%s AND b ILIKE %s")      # LIKE ignores case in SQLite, ILIKE keeps that in PostgreSQL
        self.assertEqual(a, (1, "%x%"))

    def test_question_mark_inside_text_is_left_alone(self):
        s, _ = self.t("SELECT 'why?' AS q, ? AS v", (1,))
        self.assertEqual(s, "SELECT 'why?' AS q, %s AS v")

    def test_percent_in_sql_is_escaped_only_when_params_are_used(self):
        self.assertEqual(self.t("SELECT '100%' x WHERE a=?", (1,))[0], "SELECT '100%%' x WHERE a=%s")
        self.assertEqual(self.t("SELECT '100%' x")[0], "SELECT '100%' x")

    def test_now_and_insert_or_ignore(self):
        s, _ = self.t("UPDATE a SET at=datetime('now') WHERE id=?", (1,))
        self.assertIn("to_char(timezone('utc', now())", s)
        self.assertNotIn("datetime(", s)
        s, _ = self.t("INSERT OR IGNORE INTO students(user_id) VALUES(?)", (5,))
        self.assertEqual(s, "INSERT INTO students(user_id) VALUES(%s) ON CONFLICT DO NOTHING")
        s, _ = self.t("INSERT OR IGNORE INTO settings(key,value) VALUES(?,?) ON CONFLICT(key) DO NOTHING", ("a", "b"))
        self.assertEqual(s.count("ON CONFLICT"), 1)

    def test_values_are_made_safe_for_postgres(self):
        _, a = self.t("x", (True, False, dt.date(2026, 4, 1), dt.datetime(2026, 4, 1, 9, 30, 5), None, "s", 3))
        self.assertEqual(a, (1, 0, "2026-04-01", "2026-04-01 09:30:05", None, "s", 3))

    def test_schema_translation(self):
        pg = dbx.schema_to_pg(dbx.read_schema(BASE))
        import re
        body = re.sub(r"--[^\n]*", "", pg)
        for bad in ("AUTOINCREMENT", "datetime(", "PRAGMA"):
            self.assertNotIn(bad, body)
        self.assertIn("GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", body)
        self.assertNotRegex(body, r"\bREAL\b")
        self.assertIn("users", IDS); self.assertIn("invoices", IDS)
        self.assertNotIn("settings", IDS); self.assertNotIn("counters", IDS)   # no id column, so no RETURNING id

    def test_row_and_numbers(self):
        r = dbx.Row(["id", "n"], [7, 9])
        self.assertEqual((r["id"], r[0], r[1], dict(r)), (7, 7, 9, {"id": 7, "n": 9}))
        self.assertEqual(dbx._py(decimal.Decimal("12")), 12)
        self.assertIsInstance(dbx._py(decimal.Decimal("12")), int)
        self.assertEqual(dbx._py(decimal.Decimal("12.5")), 12.5)
        self.assertEqual(dbx.normalise_url("postgres://u:p@h/db"), "postgresql://u:p@h/db")
        self.assertTrue(dbx.is_postgres("postgresql://x")); self.assertFalse(dbx.is_postgres("")); self.assertFalse(dbx.is_postgres("/tmp/a.db"))


class FakePG:
    """Stands in for psycopg: records every statement and answers from a small script."""

    def __init__(self):
        self.log, self.answers, self.connect_kw, self.commits = [], {}, {}, 0
        self.errors = types.SimpleNamespace(IntegrityError=type("IntegrityError", (Exception,), {}))

    def connect(self, url, **kw):
        self.url, self.connect_kw = url, kw
        return self

    def cursor(self):
        return FakeCursor(self)

    def commit(self): self.commits += 1
    def rollback(self): pass
    def close(self): pass


class FakeCursor:
    def __init__(self, pg):
        self.pg, self.rowcount, self.description, self._rows = pg, 1, None, []

    def execute(self, sql, params=None):
        self.pg.log.append((sql, params))
        for key, (cols, rows) in self.pg.answers.items():
            if key in sql:
                self.description = [types.SimpleNamespace(name=c) for c in cols]; self._rows = list(rows); break
        return self

    def fetchone(self): return self._rows.pop(0) if self._rows else None
    def fetchall(self): r, self._rows = self._rows, []; return r


class PostgresPath(unittest.TestCase):
    def setUp(self):
        self.fake = FakePG()
        self._old = dbx.psycopg
        dbx.psycopg = self.fake
        self.conn = dbx.Conn("postgres://u:p@host:6543/db", None, IDS)

    def tearDown(self):
        dbx.psycopg = self._old

    def test_connection_is_pooler_safe(self):
        self.assertEqual(self.fake.url, "postgresql://u:p@host:6543/db")
        self.assertIsNone(self.fake.connect_kw["prepare_threshold"])   # transaction poolers cannot keep prepared statements

    def test_insert_into_table_with_id_returns_lastrowid(self):
        self.fake.answers["INSERT INTO courses"] = (["id"], [(41,)])
        cur = self.conn.execute("INSERT INTO courses(name) VALUES(?)", ("Arabic",))
        sql, params = self.fake.log[-1]
        self.assertEqual(sql, "INSERT INTO courses(name) VALUES(%s) RETURNING id")
        self.assertEqual((cur.lastrowid, params), (41, ("Arabic",)))

    def test_insert_without_id_column_has_no_returning(self):
        self.conn.execute("INSERT OR IGNORE INTO students(user_id) VALUES(?)", (3,))
        self.assertNotIn("RETURNING", self.fake.log[-1][0])

    def test_conflict_with_no_row_gives_no_id(self):
        cur = self.conn.execute("INSERT INTO invoices(period) VALUES(?) ON CONFLICT (enrollment_id, period) DO NOTHING", ("2026-04",))
        self.assertIsNone(cur.lastrowid)
        self.assertTrue(self.fake.log[-1][0].endswith("DO NOTHING RETURNING id"))

    def test_rows_read_by_name_and_position_with_plain_numbers(self):
        self.fake.answers["FROM payments"] = (["n", "who"], [(decimal.Decimal("350"), "Aisha")])
        r = self.conn.execute("SELECT SUM(amount_mvr) n, 'x' who FROM payments WHERE id=?", (1,)).fetchone()
        self.assertEqual((r["n"], r[0], r["who"]), (350, 350, "Aisha"))
        self.assertIsInstance(r["n"], int)
        self.assertIsNone(self.conn.execute("SELECT 1 FROM nothing_here").fetchone())

    def test_schema_setup_runs_once_per_schema_version(self):
        base = BASE
        self.fake.answers["information_schema"] = (["column_name"], [("attachment",), ("attachment_name",), ("permissions",)])
        dbx.init_schema(self.conn, base)
        text = " ".join(s for s, _ in self.fake.log)
        self.assertIn("pg_advisory_xact_lock", text)
        self.assertIn("GENERATED BY DEFAULT AS IDENTITY", text)
        # second start with the same schema: recorded version matches, so the big script is skipped
        version_row = [p for s, p in self.fake.log if s.startswith("INSERT INTO schema_meta")][0][0]
        self.fake.log.clear(); self.fake.answers["SELECT version FROM schema_meta"] = (["version"], [(version_row,)])
        dbx.init_schema(self.conn, base)
        self.assertNotIn("GENERATED BY DEFAULT", " ".join(s for s, _ in self.fake.log))


class FakeS3:
    """The few boto3 calls the portal makes, kept in memory."""
    class Err(Exception):
        def __init__(self, code): self.response = {"Error": {"Code": code}}

    def __init__(self): self.objects = {}

    def put_object(self, Bucket, Key, Body, ContentType=None): self.objects[(Bucket, Key)] = (bytes(Body), ContentType)

    def get_object(self, Bucket, Key):
        if (Bucket, Key) not in self.objects: raise self.Err("NoSuchKey")
        return {"Body": io.BytesIO(self.objects[(Bucket, Key)][0])}

    def delete_object(self, Bucket, Key): self.objects.pop((Bucket, Key), None)


class Backends(unittest.TestCase):
    def check(self, st):
        st.put("learning", "a.pdf", PDF)
        self.assertEqual(st.read("learning", "a.pdf"), PDF)
        self.assertEqual(st.read("learning", "../../a.pdf"), PDF)         # path tricks are reduced to the bare file name
        with self.assertRaises(FileNotFoundError): st.read("learning", "missing.pdf")
        st.delete("learning", "a.pdf"); st.delete("learning", "a.pdf")    # deleting twice is fine
        with self.assertRaises(FileNotFoundError): st.read("learning", "a.pdf")

    def test_local(self):
        st = storage.LocalStorage(tempfile.mkdtemp())
        self.check(st)
        st.put("ids", "x.pdf", PDF)
        self.assertTrue(os.path.exists(os.path.join(st.root, "x.pdf")))                  # ID copies stay where older installs keep them
        self.assertTrue(os.path.isdir(os.path.join(st.root, "slips")))

    def test_s3(self):
        fake = FakeS3(); st = storage.S3Storage(fake, "bk", prefix="portal/")
        self.check(st)
        st.put("slips", "s.png", b"\x89PNG..")
        self.assertIn(("bk", "portal/slips/s.png"), fake.objects)
        self.assertEqual(fake.objects[("bk", "portal/slips/s.png")][1], "image/png")

    def test_make_picks_backend(self):
        self.assertEqual(storage.make({}, tempfile.mkdtemp()).kind, "local")
        sentinel = object()
        self.assertIs(storage.make({"STORAGE": sentinel}, "x"), sentinel)

    def test_upload_limits(self):
        self.assertEqual(common.cap_mb(20), 20)
        old = common.ON_VERCEL
        try:
            common.ON_VERCEL = True
            self.assertEqual(common.cap_mb(20), 4); self.assertEqual(common.cap_mb(2), 2)   # never above what Vercel can carry
        finally:
            common.ON_VERCEL = old

    def test_save_private_goes_through_the_store(self):
        fake = FakeS3(); st = storage.S3Storage(fake, "bk")
        f = types.SimpleNamespace(filename="slip.pdf", read=io.BytesIO(PDF).read)
        name, digest, shown = common.save_private(f, st, "slips")
        self.assertIn(("bk", f"slips/{name}"), fake.objects)
        self.assertEqual((shown, len(digest)), ("slip.pdf", 64))
        bad = types.SimpleNamespace(filename="slip.pdf", read=io.BytesIO(b"MZ nope").read)
        with self.assertRaises(ValueError): common.save_private(bad, st, "slips")
        self.assertEqual(len(fake.objects), 1)                               # a refused file is never stored


class AppWithBucket(unittest.TestCase):
    """The real app with every upload going to the (fake) bucket instead of the disk."""

    @classmethod
    def setUpClass(cls):
        tmp = tempfile.mkdtemp()
        os.environ["DATABASE_PATH"] = os.path.join(tmp, "h.db")
        os.environ["ADMIN_EMAIL"] = "admin@h.test"; os.environ["ADMIN_PASSWORD"] = "AdminPass123"
        import importlib; importlib.reload(sys.modules["seed"]) if "seed" in sys.modules else importlib.import_module("seed")
        from app import create_app
        cls.s3 = FakeS3()
        cls.app = create_app({"DATABASE_PATH": os.environ["DATABASE_PATH"], "STORAGE": storage.S3Storage(cls.s3, "bk"), "APPLY_LIMIT": 100})
        cls.c = cls.app.test_client()
        cls.a = cls.login("admin@h.test", "AdminPass123")

    @classmethod
    def login(cls, email, pw):
        return {"Authorization": "Bearer " + cls.c.post("/api/auth/login", json={"email": email, "password": pw}).get_json()["token"]}

    def keys(self, area): return [k for (_, k) in self.s3.objects if k.startswith(area + "/")]

    def test_admission_id_copy_lives_in_the_bucket_and_is_removed_on_request(self):
        r = self.c.post("/api/public/apply", content_type="multipart/form-data", data={
            "full_name": "Hawwa Ibrahim", "date_of_birth": (dt.date.today() - dt.timedelta(days=365 * 25)).isoformat(), "phone": "7771234",
            "email": "hawwa@h.test", "island": "Naifaru", "course_id": "1", "batch_id": "1", "id_card": (io.BytesIO(PDF), "id.pdf")})
        self.assertEqual(r.status_code, 201, r.get_data(as_text=True))
        self.assertEqual(len(self.keys("ids")), 1)
        aid = self.c.get("/api/applications", headers=self.a).get_json()[0]["id"]
        d = self.c.get(f"/api/applications/{aid}/file/id", headers=self.a)
        self.assertEqual((d.status_code, d.data), (200, PDF))
        self.assertEqual(self.c.get(f"/api/applications/{aid}/file/id").status_code, 401)        # still private
        self.assertEqual(self.c.post(f"/api/applications/{aid}/approve", json={"delete_files": True}, headers=self.a).status_code, 200)
        self.assertEqual(self.keys("ids"), [])
        self.assertEqual(self.c.get(f"/api/applications/{aid}/file/id", headers=self.a).status_code, 404)

    def test_tutorial_file_roundtrip_and_delete(self):
        self.c.post("/api/users", json={"email": "st@h.test", "password": "Password123", "full_name": "Stu", "role": "teacher"}, headers=self.a)
        stu = self.login("st@h.test", "Password123")   # a teacher: students can no longer post tutorials
        r = self.c.post("/api/tutorials", data={"title": "Alphabet", "file": (io.BytesIO(PDF), "alpha.pdf")}, headers=stu, content_type="multipart/form-data")
        self.assertEqual(r.status_code, 201, r.get_data(as_text=True)); tid = r.get_json()["id"]
        self.assertEqual(len(self.keys("learning")), 1)
        d = self.c.get(f"/api/tutorials/{tid}/file", headers=self.a)
        self.assertEqual((d.status_code, d.data), (200, PDF))
        self.assertIn("alpha.pdf", d.headers["Content-Disposition"])
        self.assertEqual(self.c.delete(f"/api/tutorials/{tid}", headers=stu).status_code, 200)
        self.assertEqual(self.keys("learning"), [])


class Migration(unittest.TestCase):
    """Moving an existing portal (SQLite file + uploads folder) into a new empty database and bucket keeps everything."""

    def test_copy_into_new_database_and_bucket(self):
        import migrate_to_hosted as M
        from app import create_app
        tmp = tempfile.mkdtemp()
        old_path, new_path = os.path.join(tmp, "old", "portal.db"), os.path.join(tmp, "new", "portal.db")
        os.environ["DATABASE_PATH"] = old_path; os.environ["ADMIN_EMAIL"] = "admin@m.test"; os.environ["ADMIN_PASSWORD"] = "AdminPass123"
        import importlib; importlib.reload(sys.modules["seed"]) if "seed" in sys.modules else importlib.import_module("seed")
        old = create_app({"DATABASE_PATH": old_path}); oc = old.test_client()
        tok = {"Authorization": "Bearer " + oc.post("/api/auth/login", json={"email": "admin@m.test", "password": "AdminPass123"}).get_json()["token"]}
        oc.post("/api/users", json={"email": "m@m.test", "password": "Password123", "full_name": "Mim", "role": "student"}, headers=tok)
        mt = {"Authorization": "Bearer " + oc.post("/api/auth/login", json={"email": "m@m.test", "password": "Password123"}).get_json()["token"]}
        tid = oc.post("/api/tutorials", data={"title": "Old post", "file": (io.BytesIO(PDF), "old.pdf")}, headers=tok, content_type="multipart/form-data").get_json()["id"]
        before = {t: dbx_count(old_path, t) for t in ("users", "courses", "batches", "enrollments", "tutorials", "audit_log")}

        bucket = FakeS3()
        new = create_app({"DATABASE_PATH": new_path, "STORAGE": storage.S3Storage(bucket, "bk")})
        lines = []
        dry = M.migrate(new, old_path, os.path.join(tmp, "old", "uploads"), dry_run=True, log=lines.append)
        self.assertEqual((dbx_count(new_path, "users"), len(bucket.objects)), (0, 0))        # a dry run copies nothing
        self.assertEqual(dry["tables"]["users"], before["users"])
        M.migrate(new, old_path, os.path.join(tmp, "old", "uploads"), log=lines.append)
        self.assertEqual({t: dbx_count(new_path, t) for t in before}, before)
        self.assertEqual(len(bucket.objects), 1)
        nc = new.test_client()
        nt = {"Authorization": "Bearer " + nc.post("/api/auth/login", json={"email": "m@m.test", "password": "Password123"}).get_json()["token"]}   # same password still works
        d = nc.get(f"/api/tutorials/{tid}/file", headers=nt)
        self.assertEqual((d.status_code, d.data), (200, PDF))
        with self.assertRaises(SystemExit): M.migrate(new, old_path, os.path.join(tmp, "old", "uploads"), log=lines.append)   # never into a database that has people


def dbx_count(path, table):
    import sqlite3
    return sqlite3.connect(path).execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]



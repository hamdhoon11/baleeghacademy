def build_statement(r):
    """v0.8.36: fee statement for one student (A4, several pages if needed). Voided invoices are left out; reversed payments are listed but not counted.
    r: academy, phone, student, student_code, generated (date), invoices[{number, period, course, due_date, amount_due, waived, paid, balance, status}],
       payments[{paid_on, receipt_no, invoice_number, method, amount, reversed}], totals{due, paid, balance}."""
    from reportlab.lib.pagesizes import A4
    buf = io.BytesIO()
    w, h = A4
    c = canvas.Canvas(buf, pagesize=A4, invariant=1, pageCompression=0)
    c.setTitle("Fee statement"); c.setAuthor(latin(r["academy"]))
    m, page = 40, [1]

    def header():
        c.setFillColorRGB(0.043, 0.31, 0.36); c.rect(0, h - 64, w, 64, stroke=0, fill=1); draw_logo(c, r, w, h, 64)
        c.setFillColorRGB(1, 1, 1); text(c, m, h - 34, r["academy"], "Helvetica-Bold", 18)
        text(c, m, h - 52, "Fee statement", "Helvetica", 10); text(c, w - m, h - 52, f"Page {page[0]}", "Helvetica", 9, right=True)
        c.setFillColorRGB(0.06, 0.15, 0.17)
        return h - 90

    def footer():
        c.setFillColorRGB(0.29, 0.39, 0.41)
        if r.get("phone"): text(c, m, 30, "Questions: " + str(r["phone"]), "Helvetica", 8)
        text(c, m, 20, "Generated by the Baleegh Academy portal on " + str(r["generated"]) + ". Voided invoices are not shown.", "Helvetica", 8)

    def need(y, room):
        if y - room > 50: return y
        footer(); c.showPage(); page[0] += 1
        return header()

    y = header()
    text(c, m, y, "Student", "Helvetica", 9); text(c, m + 90, y, r["student"], "Helvetica-Bold", 12, maxlen=60)
    text(c, w - m, y, "Date: " + str(r["generated"]), "Helvetica", 10, right=True); y -= 16
    if r.get("student_code"): text(c, m, y, "Student ID", "Helvetica", 9); text(c, m + 90, y, r["student_code"], "Helvetica", 10); y -= 16
    y -= 6
    tot = r["totals"]
    c.setFillColorRGB(0.92, 0.96, 0.96); c.rect(m, y - 30, w - 2 * m, 40, stroke=0, fill=1); c.setFillColorRGB(0.06, 0.15, 0.17)
    for k, (label, v) in enumerate((("Total billed", tot["due"]), ("Total paid", tot["paid"]), ("Balance to pay", tot["balance"]))):
        x = m + 12 + k * (w - 2 * m) / 3
        text(c, x, y - 4, label, "Helvetica", 9); text(c, x, y - 22, f"MVR {int(v)}", "Helvetica-Bold", 14)
    y -= 56
    cols = [("Invoice", 0), ("Period", 108), ("Course", 160), ("Due", 285), ("Billed", 345), ("Paid", 400), ("Balance", 450), ("Status", 500)]
    text(c, m, y, "Invoices", "Helvetica-Bold", 12); y -= 18
    c.setFont("Helvetica-Bold", 8)
    for label, x in cols: text(c, m + x, y, label, "Helvetica-Bold", 8)
    y -= 4; c.line(m, y, w - m, y); y -= 13
    for i in r["invoices"]:
        y = need(y, 16)
        vals = [i["number"], i["period"], i["course"], i["due_date"], str(int(i["amount_due"] - i["waived"])), str(int(i["paid"])), str(int(i["balance"])), str(i["status"]).replace("_", " ")]
        for (label, x), v in zip(cols, vals): text(c, m + x, y, v, "Helvetica", 8, maxlen=22 if label == "Course" else 18)
        y -= 14
    if not r["invoices"]: text(c, m, y, "No invoices.", "Helvetica", 9); y -= 14
    y = need(y - 10, 60)
    text(c, m, y, "Payments", "Helvetica-Bold", 12); y -= 18
    pcols = [("Date", 0), ("Receipt", 70), ("Invoice", 160), ("Method", 270), ("Amount", 360), ("", 420)]
    for label, x in pcols: text(c, m + x, y, label, "Helvetica-Bold", 8)
    y -= 4; c.line(m, y, w - m, y); y -= 13
    for p in r["payments"]:
        y = need(y, 16)
        vals = [p["paid_on"], p["receipt_no"], p["invoice_number"], str(p["method"]).replace("_", " "), "MVR " + str(int(p["amount"])), "REVERSED (not counted)" if p["reversed"] else ""]
        for (label, x), v in zip(pcols, vals): text(c, m + x, y, v, "Helvetica", 8)
        y -= 14
    if not r["payments"]: text(c, m, y, "No payments yet.", "Helvetica", 9)
    footer(); c.showPage(); c.save()
    return buf.getvalue()

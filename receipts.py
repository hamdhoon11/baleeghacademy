"""PDF receipts, built on demand from stored data so a re-download is byte-identical (reportlab with invariant=1).
No bank account numbers and no ID data ever go on a receipt. Labels are English.
v0.8.35: names and other values in Arabic or Thaana (Dhivehi) are drawn with the bundled font fonts/PortalSerif*.ttf (a trimmed GNU FreeSerif),
joined and ordered right to left by rtltext.py. Before, they printed as "????". Text in English letters still uses Helvetica, so those
PDFs are byte-for-byte what they were."""
import io
import os
from reportlab.lib.pagesizes import A5
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.pdfgen import canvas
import rtltext

FONT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fonts")
_FONTS = set()


def _unicode_font(bold):
    name = "PortalSerif-Bold" if bold else "PortalSerif"
    if name not in _FONTS:
        pdfmetrics.registerFont(TTFont(name, os.path.join(FONT_DIR, name + ".ttf"))); _FONTS.add(name)
    return name


def text(c, x, y, s, font="Helvetica", size=10, right=False, maxlen=None):
    """Draw one line. English text: the given Helvetica font. Arabic/Thaana/other: the bundled font, shaped and in right-to-left order."""
    s = str(s if s is not None else "")
    if maxlen: s = s[:maxlen]
    if rtltext.needs_unicode_font(s):
        font, s = _unicode_font(font.endswith("Bold")), rtltext.visual(s)
    if (c._fontname, c._fontsize) != (font, size): c.setFont(font, size)   # no extra command when nothing changes: English PDFs stay identical
    (c.drawRightString if right else c.drawString)(x, y, s)


def latin(s):
    return "".join(ch if ord(ch) < 256 else "?" for ch in str(s or ""))


def build(r):
    """r: dict with academy, phone, receipt_no, paid_on, student, course, batch, invoice_no, period, amount, method, reference, reversed (bool/None)."""
    buf = io.BytesIO()
    w, h = A5
    c = canvas.Canvas(buf, pagesize=A5, invariant=1, pageCompression=0)
    c.setTitle(f"Receipt {latin(r['receipt_no'])}"); c.setAuthor(latin(r["academy"]))
    m = 36
    c.setFillColorRGB(0.043, 0.31, 0.36); c.rect(0, h - 70, w, 70, stroke=0, fill=1)
    c.setFillColorRGB(1, 1, 1); text(c, m, h - 36, r["academy"], "Helvetica-Bold", 18)
    c.setFont("Helvetica", 10); c.drawString(m, h - 54, "Payment receipt")
    c.setFillColorRGB(0.06, 0.15, 0.17)
    y = h - 100
    c.setFont("Helvetica-Bold", 12); c.drawString(m, y, "Receipt no. " + latin(r["receipt_no"]))
    c.setFont("Helvetica", 10); c.drawRightString(w - m, y, "Date: " + latin(r["paid_on"]))
    y -= 14; c.line(m, y, w - m, y); y -= 26
    rows = [("Received from", r["student"]), ("Course", r["course"]), ("Batch", r["batch"]),
            ("Invoice", f"{r['invoice_no']}  ({r['period']})"), ("Payment method", r["method"])]
    if r.get("reference"): rows.append(("Reference", r["reference"]))
    for k, v in rows:
        c.setFont("Helvetica", 9); c.setFillColorRGB(0.29, 0.39, 0.41); c.drawString(m, y, k)
        c.setFont("Helvetica", 11); c.setFillColorRGB(0.06, 0.15, 0.17); text(c, m + 100, y, v, "Helvetica", 11, maxlen=48); y -= 20
    y -= 8
    c.setFillColorRGB(0.92, 0.96, 0.96); c.rect(m, y - 14, w - 2 * m, 40, stroke=0, fill=1)
    c.setFillColorRGB(0.06, 0.15, 0.17); c.setFont("Helvetica", 10); c.drawString(m + 10, y + 5, "Amount paid")
    c.setFont("Helvetica-Bold", 18); c.drawRightString(w - m - 10, y + 2, f"MVR {int(r['amount'])}")
    y -= 50
    if r.get("reversed"):
        c.setFillColorRGB(0.72, 0.26, 0.18); c.setFont("Helvetica-Bold", 14)
        c.drawString(m, y, "CANCELLED - this payment was reversed"); y -= 18
    c.setFillColorRGB(0.29, 0.39, 0.41); c.setFont("Helvetica", 8)
    if r.get("phone"): text(c, m, 40, "Questions: " + str(r["phone"]), "Helvetica", 8)
    c.drawString(m, 28, "This receipt was generated by the Baleegh Academy portal.")
    c.showPage(); c.save()
    return buf.getvalue()


def build_invoice(r):
    """Invoice PDF for admins. r: academy, phone, invoice_no, student_id, student, course, batch, period, due_date, amount, discount, amount_due, paid, balance, status."""
    buf = io.BytesIO()
    w, h = A5
    c = canvas.Canvas(buf, pagesize=A5, invariant=1, pageCompression=0)
    c.setTitle(f"Invoice {latin(r['invoice_no'])}"); c.setAuthor(latin(r["academy"]))
    m = 36
    c.setFillColorRGB(0.043, 0.31, 0.36); c.rect(0, h - 70, w, 70, stroke=0, fill=1)
    c.setFillColorRGB(1, 1, 1); text(c, m, h - 36, r["academy"], "Helvetica-Bold", 18)
    c.setFont("Helvetica", 10); c.drawString(m, h - 54, "Invoice")
    c.setFillColorRGB(0.06, 0.15, 0.17)
    y = h - 100
    c.setFont("Helvetica-Bold", 12); c.drawString(m, y, "Invoice no. " + latin(r["invoice_no"]))
    c.setFont("Helvetica", 10); c.drawRightString(w - m, y, "Due: " + latin(r["due_date"]))
    y -= 14; c.line(m, y, w - m, y); y -= 26
    rows = [("Student ID", r["student_id"]), ("Student", r["student"]), ("Course", r["course"]), ("Batch", r["batch"]),
            ("Billing period", r["period"]), ("Due date", r["due_date"]), ("Status", str(r["status"]).replace("_", " "))]
    for k, v in rows:
        c.setFont("Helvetica", 9); c.setFillColorRGB(0.29, 0.39, 0.41); c.drawString(m, y, k)
        c.setFont("Helvetica", 11); c.setFillColorRGB(0.06, 0.15, 0.17); text(c, m + 100, y, v, "Helvetica", 11, maxlen=48); y -= 20
    y -= 8

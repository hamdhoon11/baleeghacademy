    c.setFillColorRGB(0.06, 0.15, 0.17); c.setFont("Helvetica", 10); c.drawString(m + 10, y + 5, "Amount due")
    c.setFont("Helvetica-Bold", 18); c.drawRightString(w - m - 10, y + 2, f"MVR {int(r['amount_due'])}")
    y -= 36
    c.setFont("Helvetica", 9); c.setFillColorRGB(0.29, 0.39, 0.41)
    c.drawString(m, y, f"Fee MVR {int(r['amount'])}   Discount MVR {int(r['discount'])}   Paid MVR {int(r['paid'])}   Balance MVR {int(r['balance'])}")
